#!/usr/bin/env bash
# Build distributable artifacts. Requires Android NDK, JDK, maturin.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
VERSION="$(grep '^version' Cargo.toml | head -1 | cut -d'"' -f2)"
echo "Packaging tslib ${VERSION}"

mkdir -p dist/jniLibs
if command -v cargo-ndk >/dev/null; then
  cargo ndk --platform 29 -t arm64-v8a -t x86_64 \
    -o dist/jniLibs build -p tslib-jni --release --features vendored-openssl
else
  echo "cargo-ndk not installed; skipping Android .so build"
fi

if command -v javac >/dev/null; then
  mkdir -p dist/java-classes
  javac -d dist/java-classes java/src/main/java/dev/tslib/*.java
else
  echo "javac not found; skipping Java classes"
fi

cargo build -p tslib-ffi --release
# cbindgen header is generated by crates/tslib-ffi/build.rs

if command -v maturin >/dev/null; then
  maturin build -m crates/tslib-python/Cargo.toml --release --out dist/wheels
else
  echo "maturin not installed; skipping Python wheel"
fi

echo "Artifacts in $ROOT/dist"
